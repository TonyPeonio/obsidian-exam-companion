import { App, Notice, PluginSettingTab, Setting } from "obsidian";
import type ExamCompanionPlugin from "./main";
import { DEFAULT_SETTINGS } from "./settings";

export class ExamCompanionSettingTab extends PluginSettingTab {
	constructor(
		app: App,
		private plugin: ExamCompanionPlugin,
	) {
		super(app, plugin);
	}

	display(): void {
		const { containerEl } = this;
		containerEl.empty();
		const s = this.plugin.settings;

		new Setting(containerEl).setName("Model").setHeading();

		new Setting(containerEl)
			.setName("Ollama URL")
			.setDesc("Where Ollama is listening. Quizzes are generated by a local model; nothing leaves your machine.")
			.addText((t) =>
				t.setPlaceholder(DEFAULT_SETTINGS.ollamaUrl).setValue(s.ollamaUrl).onChange(async (v) => {
					s.ollamaUrl = v.trim() || DEFAULT_SETTINGS.ollamaUrl;
					await this.plugin.saveSettings();
				}),
			)
			.addButton((b) =>
				b.setButtonText("Test connection").onClick(async () => {
					try {
						const version = await this.plugin.client.version();
						const models = await this.plugin.client.listModels();
						const has = models.some((m) => m.name === s.model);
						new Notice(`Connected to Ollama ${version} (${models.length} models).${has ? "" : ` Model "${s.model}" is not installed: run \`ollama pull ${s.model}\`.`}`, 8000);
					} catch (err) {
						new Notice(`Connection failed: ${(err as Error).message}`, 8000);
					}
				}),
			);

		const modelSetting = new Setting(containerEl).setName("Chat model").setDesc("Any Ollama chat model. qwen3.5:9b fits a 12 GB GPU; qwen3.5:4b for smaller cards.");
		modelSetting.addDropdown(async (d) => {
			d.addOption(s.model, s.model);
			d.setValue(s.model);
			try {
				const models = await this.plugin.client.listModels();
				d.selectEl.empty();
				const names = models.filter((m) => !/embed/i.test(m.name)).map((m) => m.name);
				if (!names.includes(s.model)) names.unshift(s.model);
				for (const n of names) d.addOption(n, n);
				d.setValue(s.model);
			} catch {
				// Ollama unreachable: keep the single current value.
			}
			d.onChange(async (v) => {
				s.model = v;
				await this.plugin.saveSettings();
			});
		});
		modelSetting.addText((t) =>
			t.setPlaceholder("or type a model name").onChange(async (v) => {
				if (!v.trim()) return;
				s.model = v.trim();
				await this.plugin.saveSettings();
			}),
		);

		new Setting(containerEl)
			.setName("Context window (num_ctx)")
			.setDesc("Tokens the model can see. A quiz sends the day's topic text; 16384 is plenty for a few lectures.")
			.addText((t) =>
				t.setValue(String(s.numCtx)).onChange(async (v) => {
					const n = parseInt(v, 10);
					if (Number.isFinite(n) && n >= 2048 && n <= 262144) {
						s.numCtx = n;
						await this.plugin.saveSettings();
					}
				}),
			);

		new Setting(containerEl)
			.setName("Thinking mode")
			.setDesc("Let thinking-capable models reason before answering. Off is faster; quizzes rarely need it.")
			.addToggle((t) =>
				t.setValue(s.thinking).onChange(async (v) => {
					s.thinking = v;
					await this.plugin.saveSettings();
				}),
			);

		new Setting(containerEl).setName("Study plan").setHeading();

		new Setting(containerEl)
			.setName("Questions per quiz")
			.addSlider((sl) =>
				sl
					.setLimits(3, 15, 1)
					.setValue(s.questionsPerQuiz)
					.onChange(async (v) => {
						s.questionsPerQuiz = v;
						await this.plugin.saveSettings();
					}),
			);

		new Setting(containerEl)
			.setName("Default minutes per day")
			.addSlider((sl) =>
				sl
					.setLimits(10, 240, 5)
					.setValue(s.minutesPerDay)
					.onChange(async (v) => {
						s.minutesPerDay = v;
						await this.plugin.saveSettings();
					}),
			);

		new Setting(containerEl)
			.setName("Exams folder")
			.setDesc("Where plan notes are created.")
			.addText((t) =>
				t.setPlaceholder(DEFAULT_SETTINGS.examsFolder).setValue(s.examsFolder).onChange(async (v) => {
					s.examsFolder = v.trim().replace(/^\/+|\/+$/g, "") || DEFAULT_SETTINGS.examsFolder;
					await this.plugin.saveSettings();
				}),
			);

		new Setting(containerEl)
			.setName("Flashcards folder")
			.setDesc("Export flashcards writes Question::Answer lines (the Spaced Repetition plugin's format) to <folder>/<Course>.md.")
			.addText((t) =>
				t.setPlaceholder(DEFAULT_SETTINGS.flashcardsFolder).setValue(s.flashcardsFolder).onChange(async (v) => {
					s.flashcardsFolder = v.trim().replace(/^\/+|\/+$/g, "") || DEFAULT_SETTINGS.flashcardsFolder;
					await this.plugin.saveSettings();
				}),
			);
	}
}
